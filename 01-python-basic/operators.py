# 算术运算符
a = 10
b = 3
print(f"加法: {a} + {b} = {a + b}")
print(f"减法: {a} - {b} = {a - b}")
print(f"乘法: {a} * {b} = {a * b}")
print(f"除法: {a} / {b} = {a / b}")
print(f"整除: {a} // {b} = {a // b}")
print(f"取余: {a} % {b} = {a % b}")
print(f"幂运算: {a} ** {b} = {a ** b}")

# 比较运算符
print(f"等于: {a} == {b} = {a == b}")
print(f"不等于: {a} != {b} = {a != b}")
print(f"大于: {a} > {b} = {a > b}")
print(f"小于: {a} < {b} = {a < b}")

# 逻辑运算符
x = True
y = False
print(f"与运算: {x} and {y} = {x and y}")
print(f"或运算: {x} or {y} = {x or y}")
print(f"非运算: not {x} = {not x}")
